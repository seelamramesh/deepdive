from types import SimpleNamespace
import asyncio

import pytest

from app.core.mesh_gateway import MeshGateway, _parse_json_object


def test_gateway_module_accepts_trailing_text_parser_contract():
    content = '{"subquestions": []}\nGenerated by model.'
    assert _parse_json_object(content, "planner") == {"subquestions": []}


def test_gateway_parser_accepts_fenced_json():
    assert _parse_json_object('```json\n{"queries": []}\n```', "search") == {"queries": []}


def test_gateway_parser_rejects_array():
    with pytest.raises(ValueError, match="expected object"):
        _parse_json_object('[1, 2]', "planner")


@pytest.mark.asyncio
async def test_token_counts_come_from_response_metadata():
    class Completions:
        async def create(self, **kwargs):
            return SimpleNamespace(
                choices=[SimpleNamespace(message=SimpleNamespace(content='{"total_tokens": 99999}'), finish_reason="stop")],
                usage=SimpleNamespace(prompt_tokens=12, completion_tokens=4, total_tokens=16),
            )

    gateway = MeshGateway()
    gateway._client = SimpleNamespace(chat=SimpleNamespace(completions=Completions()))
    await gateway.complete("judge", "system", "user")
    call = gateway.drain_calls()[0]
    assert call.total_tokens == 16
    assert call.prompt_tokens == 12
    assert call.completion_tokens == 4


@pytest.mark.asyncio
async def test_gateway_retries_invalid_json_and_records_attempts(monkeypatch):
    responses = [
        SimpleNamespace(choices=[SimpleNamespace(
            message=SimpleNamespace(content='```json\n{"arguments": ['),
            finish_reason="length",
        )]),
        SimpleNamespace(choices=[SimpleNamespace(
            message=SimpleNamespace(content='{"arguments": []}'),
            finish_reason="stop",
        )]),
    ]

    class Completions:
        async def create(self, **kwargs):
            assert kwargs["max_tokens"] > 0
            return responses.pop(0)

    gateway = MeshGateway()
    gateway._client = SimpleNamespace(chat=SimpleNamespace(completions=Completions()))
    monkeypatch.setattr("app.core.mesh_gateway.settings.mesh_json_attempts", 2)

    result = await gateway.complete("prosecutor", "system", "user")
    calls = gateway.drain_calls()

    assert result == {"arguments": []}
    assert [call.success for call in calls] == [False, True]
    assert calls[0].finish_reason == "length"
    assert calls[0].input_hash != calls[1].input_hash


