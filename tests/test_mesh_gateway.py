@pytest.mark.asyncio
async def test_gateway_audit_calls_are_isolated_per_async_task(monkeypatch):
    class Completions:
        async def create(self, **kwargs):
            await asyncio.sleep(0)
            return SimpleNamespace(choices=[SimpleNamespace(
                message=SimpleNamespace(content='{"ok": true}'),
                finish_reason="stop",
            )])

    gateway = MeshGateway()
    gateway._client = SimpleNamespace(chat=SimpleNamespace(completions=Completions()))

    async def execute(agent):
        await gateway.complete(agent, "system", "user")
        return [call.agent for call in gateway.drain_calls()]

    first, second = await asyncio.gather(execute("first"), execute("second"))

    assert first == ["first"]
    assert second == ["second"]


@pytest.mark.asyncio
async def test_transport_failure_is_recorded_without_invented_usage():
    class Completions:
        async def create(self, **kwargs):
            raise TimeoutError('possibly sensitive request details')

    gateway = MeshGateway()
    gateway._client = SimpleNamespace(chat=SimpleNamespace(completions=Completions()))
    with pytest.raises(TimeoutError):
        await gateway.complete('judge', 'system', 'user')
    calls = gateway.drain_calls()
    assert len(calls) == 1
    assert calls[0].success is False
    assert calls[0].total_tokens is None
    assert calls[0].error == 'TimeoutError'


